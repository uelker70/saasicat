// Third build pass: replace the per-entry CommonJS bundles with thin
// re-exports of the single `dist/_entries.cjs` produced by
// `tsup.cjs.config.ts`.
//
// Why this exists: esbuild only code-splits ESM, so tsup's per-entry CJS
// output copies every shared module into each entry. Each copy carries its own
// class objects, and Nest resolves providers by class reference — so a service
// registered via one entry cannot be injected from another. See
// `src/_all-entries.ts` for the full rationale.
//
// After this pass every entry hands out the SAME objects, in CJS as in ESM.
// The `.d.cts` declarations from the main build stay untouched: types have no
// runtime identity, and each entry keeps its own narrow surface.
//
// The entry list comes from `package.json` `exports` via `entries.mjs`, so an
// entry can never be silently skipped here and left as a duplicated bundle.

import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

import { packageRoot, publicEntries } from './entries.mjs';

const dist = join(packageRoot, 'dist');
const sharedBundle = join(dist, '_entries.cjs');

if (!existsSync(sharedBundle)) {
    throw new Error(
        'dist/_entries.cjs is missing — run `tsup --config tsup.cjs.config.ts` before this script.',
    );
}

const entries = publicEntries();
const bundleExports = Object.keys(await import(`file://${sharedBundle}`));

const missing = entries.filter((e) => !bundleExports.includes(e.namespace));
if (missing.length > 0) {
    throw new Error(
        `src/_all-entries.ts does not re-export ${missing
            .map((e) => `\`${e.namespace}\` (for "${e.exportPath}")`)
            .join(', ')}. Add the namespace there, or the entry keeps its own ` +
            'duplicated CJS bundle and its classes stop matching the other entries.',
    );
}

for (const entry of entries) {
    const target = join(dist, `${entry.distBase}.cjs`);
    if (!existsSync(target)) {
        throw new Error(
            `dist/${entry.distBase}.cjs was never built — "${entry.exportPath}" is in ` +
                'package.json exports but missing from the tsup entry list.',
        );
    }

    const requirePath = relative(dirname(target), sharedBundle).split('\\').join('/');
    const specifier = requirePath.startsWith('.') ? requirePath : `./${requirePath}`;

    await writeFile(
        target,
        `'use strict';\n` +
            `// Generated by scripts/build-cjs-stubs.mjs — do not edit.\n` +
            `// Thin re-export so every entry shares one set of class objects.\n` +
            `module.exports = require('${specifier}').${entry.namespace};\n`,
        'utf8',
    );
}

// A stub that still contained bundled code would mean the pass silently did
// nothing — catch that rather than shipping duplicated classes again.
for (const entry of entries) {
    const contents = await readFile(join(dist, `${entry.distBase}.cjs`), 'utf8');
    if (contents.includes('__toCommonJS')) {
        throw new Error(`dist/${entry.distBase}.cjs was not replaced by a stub`);
    }
}

console.log(`[build-cjs-stubs] ${entries.length} CJS entries now share dist/_entries.cjs`);
