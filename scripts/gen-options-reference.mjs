#!/usr/bin/env node
// Generates `docs/reference/options.md` from the rule table in
// `@saasicat/nest/platform`.
//
// The page exists because every rule's boot error ends in a link to it, and a
// link that resolves to a hand-maintained page is a link that will one day
// describe a rule that no longer exists. So the page is not maintained: it is
// derived, and `tests/options-reference-is-generated.test.js` fails the build
// when the committed file and the rules disagree.
//
//   node scripts/gen-options-reference.mjs            print what it would write
//   node scripts/gen-options-reference.mjs --write    write the file
//
// Requires `@saasicat/nest` to be built — the rules are read from `dist/`, the
// same way the test suites read everything else.

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(REPO_ROOT, 'docs/reference/options.md');

const { PLATFORM_RULES } = await import(
    new URL('../packages/nest/dist/platform/index.js', import.meta.url).href
);

/**
 * The area a rule belongs to — the part of its id before the dot.
 *
 * Grouping by it rather than by option name because several options share one
 * area (`promoCodes` has two rules) and one rule spans two (`entitlement` is
 * required by `tenantBilling`). The id is the thing that appears in the boot
 * error, so it is the thing a reader arrives with.
 */
const areaOf = (rule) => rule.id.split('.')[0];

/**
 * Wraps prose at 80 columns.
 *
 * The messages are written as one long string — they are read in a terminal,
 * where the terminal wraps them. On the page they would be one 264-column line,
 * which markdownlint's default `line-length` rejects and which Prettier leaves
 * alone (`proseWrap: preserve`). So the generator wraps, and the source of the
 * text stays a single sentence with no line breaks baked into it.
 */
function wrap(text, width = 80) {
    const out = [];
    let line = '';
    for (const word of text.split(' ')) {
        if (line && `${line} ${word}`.length > width) {
            out.push(line);
            line = word;
        } else {
            line = line ? `${line} ${word}` : word;
        }
    }
    if (line) out.push(line);
    return out;
}

/**
 * A configuration a rule's `message` can be called with.
 *
 * The messages name what is missing, and here nothing is configured at all, so
 * each renders its "everything is absent" form — which is the form a reader of
 * this page is most likely holding.
 */
const EMPTY = { options: {}, adapters: {} };

function render() {
    const areas = new Map();
    for (const rule of PLATFORM_RULES) {
        const area = areaOf(rule);
        areas.set(area, [...(areas.get(area) ?? []), rule]);
    }

    const lines = [
        '<!-- Generated by scripts/gen-options-reference.mjs. Do not edit. -->',
        '',
        '# Configuration rules',
        '',
        '`SaaSiCatModule.forRoot()` checks its options against the rules below before it',
        'assembles anything, and reports **every** violation at once rather than the first.',
        'A failing boot names each rule by id and links back to this page.',
        '',
        'This file is generated from `PLATFORM_RULES` in',
        '`@saasicat/nest/platform`. Change the rule, not the page.',
        '',
        `There are ${PLATFORM_RULES.length} rules, in ${areas.size} areas.`,
        '',
    ];

    for (const [area, rules] of areas) {
        lines.push(`## ${area}`, '');
        for (const rule of rules) {
            // The heading text IS the id, so the anchor the rule's `docs`
            // link points at is `headingSlug(rule.id)` by construction.
            lines.push(`### ${rule.id}`, '');
            const message = typeof rule.message === 'string' ? rule.message : rule.message(EMPTY);
            lines.push(...wrap(`${message.charAt(0).toUpperCase()}${message.slice(1)}`), '');
        }
    }

    lines.push(
        '## Reading a failed boot',
        '',
        '```text',
        'SaaSiCatModule.forRoot: 2 configuration problems:',
        '  1. [core.adapters-bound] the core adapters are missing: mfa, rlsBypass. …',
        '     → …/options.md#core',
        '  2. [catalog.requires-persistence] catalog is enabled, but …',
        '     → …/options.md#catalog',
        '```',
        '',
        'The list is complete: fixing all of them is one restart, not one per line.',
        '',
    );

    return lines.join('\n');
}

const content = render();
if (process.argv.includes('--write')) {
    writeFileSync(TARGET, content);
    console.log(`Wrote ${TARGET} (${PLATFORM_RULES.length} rules)`);
} else {
    process.stdout.write(content);
}
